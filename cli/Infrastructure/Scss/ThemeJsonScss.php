<?php

declare(strict_types=1);

namespace ItalyStrap\ThemeJsonGenerator\Cli\Infrastructure\Scss;

final readonly class ThemeJsonScss
{
    private const PRESETS = [
        'color' => ['palette' => 'color', 'gradients' => 'gradient', 'duotone' => 'duotone'],
        'typography' => [
            'fontSizes' => 'font-size',
            'fontFamilies' => 'font-family',
            'textShadowPresets' => 'text-shadow',
        ],
        'spacing' => ['spacingSizes' => 'spacing'],
        'shadow' => ['presets' => 'shadow'],
        'dimensions' => ['aspectRatios' => 'aspect-ratio', 'dimensionSizes' => 'dimension'],
        'border' => ['radiusSizes' => 'border-radius'],
    ];

    /** @param array<array-key, mixed> $data */
    public function generate(array $data): string
    {
        $settings = $this->object($data['settings'] ?? [], 'settings');
        $properties = $this->settings($settings);
        foreach ($this->object($settings['blocks'] ?? [], 'settings.blocks') as $block) {
            $properties = [...$properties, ...$this->settings($this->object($block, 'block settings'))];
        }

        $properties = [...$properties, ...$this->layout($settings), ...$this->rootPadding($data, $settings)];
        $properties = \array_values(\array_unique($properties));
        \sort($properties, SORT_STRING);
        $content = "// Generated by theme-json. Do not edit.\n";
        foreach ($properties as $property) {
            $content .= \sprintf('$%s: var(%s);' . "\n", \substr($property, 2), $property);
        }

        return $content;
    }

    /**
     * @param array<array-key, mixed> $settings
     * @return list<string>
     */
    private function settings(array $settings): array
    {
        $properties = [];
        foreach (self::PRESETS as $section => $categories) {
            $values = $this->object($settings[$section] ?? [], 'settings.' . $section);
            foreach ($categories as $key => $type) {
                $properties = [...$properties, ...$this->presets($values[$key] ?? [], $type)];
            }
        }

        $custom = $this->object($settings['custom'] ?? [], 'settings.custom');
        return [...$properties, ...$this->custom($custom, '--wp--custom--')];
    }

    /** @return list<string> */
    private function presets(mixed $presets, string $type): array
    {
        if (!\is_array($presets) || !\array_is_list($presets)) {
            throw new \InvalidArgumentException('Expected a list of ' . $type . ' presets.');
        }

        $names = [];
        foreach ($presets as $preset) {
            $preset = $this->object($preset, $type . ' preset');
            $slug = $preset['slug'] ?? null;
            if (!\is_string($slug) || $slug === '') {
                throw new \InvalidArgumentException('Every ' . $type . ' preset must have a non-empty string slug.');
            }

            $name = '--wp--preset--' . $type . '--' . $this->normalize($slug);
            $this->register($names, $name, $slug);
        }

        return \array_keys($names);
    }

    /**
     * @param array<array-key, mixed> $values
     * @return list<string>
     */
    private function custom(array $values, string $prefix): array
    {
        $names = [];
        $properties = [];
        foreach ($values as $key => $value) {
            $name = $prefix . $this->normalize((string) $key);
            $this->register($names, $name, (string) $key);
            if (\is_array($value)) {
                $properties = [...$properties, ...$this->custom($value, $name . '--')];
                continue;
            }

            if (!\is_string($value) && !\is_int($value) && !\is_float($value)) {
                throw new \InvalidArgumentException('Custom setting ' . $key . ' must contain a CSS value.');
            }

            $properties[] = $name;
        }

        return $properties;
    }

    /**
     * @param array<array-key, mixed> $settings
     * @return list<string>
     */
    private function layout(array $settings): array
    {
        $layout = $this->object($settings['layout'] ?? [], 'settings.layout');
        $properties = [];
        foreach (['contentSize' => 'content-size', 'wideSize' => 'wide-size'] as $key => $name) {
            if (\is_string($layout[$key] ?? null) && $layout[$key] !== '') {
                $properties[] = '--wp--style--global--' . $name;
            }
        }

        return $properties;
    }

    private function normalize(string $name): string
    {
        // Separate words, acronyms and numbers, matching WordPress preset naming.
        \preg_match_all(
            '/\p{Lu}?\p{Ll}+|\p{Lu}+(?!\p{Ll})|\d*(?:1ST|2ND|3RD|(?![123])\dTH)(?=\b|[a-z_])'
            . '|\d*(?:1st|2nd|3rd|(?![123])\dth)(?=\b|[A-Z_])|\d+|[^\W\d_]+/u',
            \str_replace("'", '', $name),
            $words
        );
        $normalized = \strtolower(\implode('-', $words[0]));
        if ($normalized === '') {
            throw new \InvalidArgumentException('Cannot generate a CSS variable name from "' . $name . '".');
        }

        return $normalized;
    }

    /**
     * @param array<array-key, mixed> $data
     * @param array<array-key, mixed> $settings
     * @return list<string>
     */
    private function rootPadding(array $data, array $settings): array
    {
        if (($settings['useRootPaddingAwareAlignments'] ?? false) !== true) {
            return [];
        }

        $styles = $this->object($data['styles'] ?? [], 'styles');
        $spacing = $this->object($styles['spacing'] ?? [], 'styles.spacing');
        $padding = $spacing['padding'] ?? [];
        if (!\is_array($padding)) {
            return [];
        }

        $properties = [];
        foreach (['top', 'right', 'bottom', 'left'] as $side) {
            $value = $padding[$side] ?? null;
            if ((\is_string($value) && $value !== '') || \is_int($value) || \is_float($value)) {
                $properties[] = '--wp--style--root--padding-' . $side;
            }
        }

        return $properties;
    }

    /** @param array<string, string> $names */
    private function register(array &$names, string $name, string $source): void
    {
        if (\array_key_exists($name, $names) && $names[$name] !== $source) {
            throw new \InvalidArgumentException('CSS variable name collision: ' . $name);
        }

        $names[$name] = $source;
    }

    /** @return array<array-key, mixed> */
    private function object(mixed $value, string $location): array
    {
        if (!\is_array($value)) {
            throw new \InvalidArgumentException('Expected an object at ' . $location . '.');
        }

        return $value;
    }
}
