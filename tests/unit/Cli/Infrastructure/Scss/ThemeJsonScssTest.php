<?php

declare(strict_types=1);

namespace ItalyStrap\Tests\Unit\Cli\Infrastructure\Scss;

use ItalyStrap\Tests\UnitTestCase;
use ItalyStrap\ThemeJsonGenerator\Cli\Infrastructure\Scss\ThemeJsonScss;
use ScssPhp\ScssPhp\Compiler;

final class ThemeJsonScssTest extends UnitTestCase
{
    public function testItExportsSortedUniqueReferencesFromRootAndBlockSettings(): void
    {
        $scss = (new ThemeJsonScss())->generate(['settings' => [
            'color' => ['palette' => [['slug' => 'primary', 'color' => '#fff']]],
            'custom' => ['lineHeight' => ['small' => 1.2]],
            'layout' => ['contentSize' => '40rem'],
            'blocks' => ['core/group' => [
                'color' => ['palette' => [['slug' => 'primary', 'color' => '#000']]],
                'typography' => ['fontSizes' => [['slug' => 'bodyText', 'size' => '1rem']]],
            ]],
        ]]);

        $this->assertSame(<<<'SCSS'
// Generated by theme-json. Do not edit.
$wp--custom--line-height--small: var(--wp--custom--line-height--small);
$wp--preset--color--primary: var(--wp--preset--color--primary);
$wp--preset--font-size--body-text: var(--wp--preset--font-size--body-text);
$wp--style--global--content-size: var(--wp--style--global--content-size);
SCSS
            . "\n", $scss);

        $css = (new Compiler())->compileString($scss . '.button {color: $wp--preset--color--primary;}')->getCss();
        $this->assertStringContainsString('color: var(--wp--preset--color--primary)', $css);
    }

    public function testItCoversEverySupportedPresetCategory(): void
    {
        $preset = [['slug' => 'sample']];
        $scss = (new ThemeJsonScss())->generate(['settings' => [
            'color' => ['palette' => $preset, 'gradients' => $preset, 'duotone' => $preset],
            'typography' => ['fontSizes' => $preset, 'fontFamilies' => $preset, 'textShadowPresets' => $preset],
            'spacing' => ['spacingSizes' => $preset],
            'shadow' => ['presets' => $preset],
            'dimensions' => ['aspectRatios' => $preset, 'dimensionSizes' => $preset],
            'border' => ['radiusSizes' => $preset],
        ]]);
        $categories = ['color', 'gradient', 'duotone', 'font-size', 'font-family', 'text-shadow',
            'spacing', 'shadow', 'aspect-ratio', 'dimension', 'border-radius'];
        foreach ($categories as $category) {
            $this->assertStringContainsString('var(--wp--preset--' . $category . '--sample)', $scss);
        }
    }

    public function testItRejectsNormalizedNameCollisions(): void
    {
        $this->expectException(\InvalidArgumentException::class);
        $this->expectExceptionMessage('CSS variable name collision');
        (new ThemeJsonScss())->generate(['settings' => ['custom' => ['myColor' => 'red', 'my-color' => 'blue']]]);
    }

    public function testItRejectsMalformedPresets(): void
    {
        $this->expectException(\InvalidArgumentException::class);
        $this->expectExceptionMessage('slug');
        (new ThemeJsonScss())->generate(['settings' => ['color' => ['palette' => [['color' => 'red']]]]]);
    }

    public function testItProducesAValidEmptyPartial(): void
    {
        $scss = (new ThemeJsonScss())->generate(['version' => 3]);
        $this->assertSame("// Generated by theme-json. Do not edit.\n", $scss);
        $this->assertSame('', (new Compiler())->compileString($scss)->getCss());
    }
}
